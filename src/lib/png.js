/**
 * A minimal PNG writer and bitmap text renderer.
 *
 * Social platforms reject SVG for og:image, and a share card is the main way a
 * link travels in a small town — so the OG image has to be a real raster file.
 * Node ships zlib, which is the only hard part of writing a PNG, so this needs
 * no dependency and no build-time image toolchain.
 *
 * The font is a 5x7 uppercase bitmap. It is not elegant at small sizes, but at
 * the scale an OG card is rendered it is clean and perfectly legible, and it
 * removes any question of font licensing or availability.
 */

import zlib from 'node:zlib';

/* --- PNG container -------------------------------------------------------- */

const CRC_TABLE = (() => {
  const table = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c;
  }
  return table;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const typeBuf = Buffer.from(type, 'ascii');
  const body = Buffer.concat([typeBuf, data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body), 0);
  return Buffer.concat([len, body, crc]);
}

/** Encode an RGB pixel buffer (width*height*3) as a PNG. */
export function encodePng(width, height, rgb) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;  // bit depth
  ihdr[9] = 2;  // colour type: truecolour
  ihdr[10] = 0; // deflate
  ihdr[11] = 0; // adaptive filtering
  ihdr[12] = 0; // no interlace

  // Each scanline is prefixed with its filter byte; filter 0 (None) keeps this
  // simple and still compresses well on flat-colour artwork.
  const stride = width * 3;
  const raw = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (stride + 1)] = 0;
    rgb.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride);
  }

  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

/* --- Canvas --------------------------------------------------------------- */

export function canvas(width, height, [r, g, b]) {
  const buf = Buffer.alloc(width * height * 3);
  for (let i = 0; i < buf.length; i += 3) {
    buf[i] = r; buf[i + 1] = g; buf[i + 2] = b;
  }
  return {
    width,
    height,
    data: buf,
    rect(x, y, w, h, [cr, cg, cb]) {
      for (let py = Math.max(0, y); py < Math.min(height, y + h); py++) {
        for (let px = Math.max(0, x); px < Math.min(width, x + w); px++) {
          const i = (py * width + px) * 3;
          buf[i] = cr; buf[i + 1] = cg; buf[i + 2] = cb;
        }
      }
    },
  };
}

