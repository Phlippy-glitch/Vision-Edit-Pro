/** Width in pixels of `text` at the given scale, including inter-letter gaps. */
export function textWidth(text, scale, tracking = 1) {
  const chars = String(text).toUpperCase().length;
  return chars * (5 + tracking) * scale - tracking * scale;
}

export function drawText(cv, text, x, y, scale, colour, tracking = 1) {
  let cursor = x;
  for (const raw of String(text).toUpperCase()) {
    const glyph = FONT[raw] || FONT[' '];
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 5; col++) {
        if (glyph[row][col] === '1') {
          cv.rect(cursor + col * scale, y + row * scale, scale, scale, colour);
        }
      }
    }
    cursor += (5 + tracking) * scale;
  }
  return cursor;
}
